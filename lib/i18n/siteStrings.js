import React from "react";

export function formatSiteString(template, vars = {}) {
  if (!template || typeof template !== "string") return template;
  const hasNode = Object.values(vars).some((value) => React.isValidElement(value));
  if (!hasNode) {
    return template.replace(/\{(\w+)\}/g, (_, key) =>
      vars[key] != null ? String(vars[key]) : `{${key}}`
    );
  }
  return template.split(/\{(\w+)\}/g).map((part, index) =>
    index % 2 === 1
      ? React.createElement(React.Fragment, { key: index }, vars[part] ?? `{${part}}`)
      : part
  );
}


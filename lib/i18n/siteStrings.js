/** Replace `{key}` placeholders in a string. Values may be React nodes. */
export function formatSiteString(template, vars = {}) {
  if (!template || typeof template !== "string") return template;
  const hasNode = Object.values(vars).some((v) => React.isValidElement(v));
  if (!hasNode) {
    return template.replace(/\{(\w+)\}/g, (_, k) =>
      vars[k] != null ? String(vars[k]) : `{${k}}`
    );
  }
  const parts = template.split(/\{(\w+)\}/g);
  return parts.map((part, i) => {
    if (i % 2 === 1) {
      const v = vars[part];
      return v != null
        ? React.createElement(React.Fragment, { key: i }, v)
        : `{${part}}`;
    }
    return part;
  });
}

